-- 1. Tambahkan nilai 'MODE_PIONIR' ke enum mode_penilaian_enum jika belum ada
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type typ
    JOIN pg_enum enm ON typ.oid = enm.enumtypid
    WHERE typ.typname = 'mode_penilaian_enum' AND enm.enumlabel = 'MODE_PIONIR'
  ) THEN
    ALTER TYPE public.mode_penilaian_enum ADD VALUE 'MODE_PIONIR';
  END IF;
END $$;

-- 2. Tambah kolom tgl_selesai_fase1 di periode_penilaian
ALTER TABLE public.periode_penilaian
ADD COLUMN IF NOT EXISTS tgl_selesai_fase1 TIMESTAMP WITH TIME ZONE;

-- 3. Tambah kolom bobot di tabel pertanyaan (default 0.20 untuk 5 pilar kriteria)
ALTER TABLE public.pertanyaan
ADD COLUMN IF NOT EXISTS bobot NUMERIC DEFAULT 0.20;

-- 4. Tambah kolom nilai_ckp di tabel nominee_periode
ALTER TABLE public.nominee_periode
ADD COLUMN IF NOT EXISTS nilai_ckp NUMERIC DEFAULT 0;

-- 5. Tabel Pengusul Periode (Designated Nominators)
CREATE TABLE IF NOT EXISTS public.pengusul_periode (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periode_id BIGINT NOT NULL REFERENCES public.periode_penilaian(id) ON DELETE CASCADE,
  pegawai_id BIGINT NOT NULL REFERENCES public.pegawai(id) ON DELETE CASCADE,
  token_akses UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
  is_digunakan BOOLEAN DEFAULT FALSE,
  submitted_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT uq_pengusul_periode UNIQUE (periode_id, pegawai_id)
);

CREATE INDEX IF NOT EXISTS idx_pengusul_token ON public.pengusul_periode(token_akses);
CREATE INDEX IF NOT EXISTS idx_pengusul_periode_id ON public.pengusul_periode(periode_id);

-- 6. Tabel Penilaian Pengusul (Fase 1)
CREATE TABLE IF NOT EXISTS public.penilaian_pionir_pengusul (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periode_id BIGINT NOT NULL REFERENCES public.periode_penilaian(id) ON DELETE CASCADE,
  pengusul_id BIGINT NOT NULL REFERENCES public.pegawai(id) ON DELETE CASCADE,
  kandidat_id BIGINT NOT NULL REFERENCES public.pegawai(id) ON DELETE CASCADE,
  pertanyaan_id BIGINT NOT NULL REFERENCES public.pertanyaan(id) ON DELETE CASCADE,
  skor NUMERIC NOT NULL,
  kata_kunci TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT uq_penilaian_pionir_item UNIQUE (periode_id, pengusul_id, kandidat_id, pertanyaan_id),
  CONSTRAINT chk_anti_self_pionir CHECK (pengusul_id <> kandidat_id)
);

CREATE INDEX IF NOT EXISTS idx_penilaian_pionir_periode ON public.penilaian_pionir_pengusul(periode_id);
CREATE INDEX IF NOT EXISTS idx_penilaian_pionir_kandidat ON public.penilaian_pionir_pengusul(kandidat_id);

-- 7. Tabel Suara Pemilih Umum (Fase 2 - Mode Rahasia LUBER)
CREATE TABLE IF NOT EXISTS public.suara_pionir (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periode_id BIGINT NOT NULL REFERENCES public.periode_penilaian(id) ON DELETE CASCADE,
  kandidat_id BIGINT NOT NULL REFERENCES public.pegawai(id) ON DELETE CASCADE,
  voter_hash TEXT, -- Identifier anonim untuk audit trail tanpa mengekspos identitas
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_suara_pionir_periode ON public.suara_pionir(periode_id);
CREATE INDEX IF NOT EXISTS idx_suara_pionir_kandidat ON public.suara_pionir(kandidat_id);

-- 8. Kebijakan Row Level Security (RLS) & Izin Tabel (Grants)
ALTER TABLE public.pengusul_periode ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.penilaian_pionir_pengusul ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.suara_pionir ENABLE ROW LEVEL SECURITY;

