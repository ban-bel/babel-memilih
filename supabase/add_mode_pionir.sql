USING (true)
WITH CHECK (true);

-- Penilaian Pengusul: Izinkan insert & select instrumen
DROP POLICY IF EXISTS "Allow all penilaian_pionir_pengusul" ON public.penilaian_pionir_pengusul;
CREATE POLICY "Allow all penilaian_pionir_pengusul" ON public.penilaian_pionir_pengusul
FOR ALL
TO anon, authenticated
USING (true)
WITH CHECK (true);

