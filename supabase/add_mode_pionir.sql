-- RPC: Ambil akses token PIONIR
CREATE OR REPLACE FUNCTION public.get_akses_pionir_by_token(p_token UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_res JSONB;
  v_pengusul RECORD;
  v_penilai RECORD;
  v_periode RECORD;
  v_is_kandidat BOOLEAN := FALSE;
  v_fase INTEGER := 1;
BEGIN
  -- 1. Cek tabel pengusul_periode
  SELECT pp.*, p.nama, p.nip, p.nip_baru, p.jabatan, p.foto_url
  INTO v_pengusul
  FROM public.pengusul_periode pp
  JOIN public.pegawai p ON p.id = pp.pegawai_id
  WHERE pp.token_akses = p_token;

  IF FOUND THEN
    SELECT * INTO v_periode 
    FROM public.periode_penilaian 
    WHERE id = v_pengusul.periode_id;

    IF v_periode.tgl_selesai_fase1 IS NOT NULL AND NOW() > v_periode.tgl_selesai_fase1 THEN
      v_fase := 2;
    ELSE
      v_fase := 1;
    END IF;

    v_res := jsonb_build_object(
      'is_valid', true,
      'peran', 'PENGUSUL',
      'fase', v_fase,
      'is_digunakan', COALESCE(v_pengusul.is_digunakan, false),
      'periode', row_to_json(v_periode),
      'profil', jsonb_build_object(
        'id', v_pengusul.pegawai_id,
        'nama', v_pengusul.nama,
        'nip', v_pengusul.nip,
        'nip_baru', v_pengusul.nip_baru,
        'jabatan', v_pengusul.jabatan,
        'foto_url', v_pengusul.foto_url
      )
    );
    RETURN v_res;
  END IF;

  -- 2. Cek tabel akses_penilai (Pemilih Umum)
  SELECT ap.*, p.nama, p.nip, p.nip_baru, p.jabatan, p.foto_url
  INTO v_penilai
  FROM public.akses_penilai ap
  JOIN public.pegawai p ON p.id = ap.pegawai_id
  WHERE ap.token_akses = p_token;

  IF FOUND THEN
    SELECT * INTO v_periode 
    FROM public.periode_penilaian 
    WHERE id = v_penilai.periode_id;

    -- Cek apakah pemilih ini dicalonkan sebagai kandidat
    SELECT EXISTS (
      SELECT 1 FROM public.nominee_periode 
      WHERE periode_id = v_penilai.periode_id AND pegawai_id = v_penilai.pegawai_id
    ) INTO v_is_kandidat;

    IF v_periode.tgl_selesai_fase1 IS NOT NULL AND NOW() > v_periode.tgl_selesai_fase1 THEN
      v_fase := 2;
    ELSE
      v_fase := 1;
    END IF;

    v_res := jsonb_build_object(
      'is_valid', true,
      'peran', CASE WHEN v_is_kandidat THEN 'KANDIDAT' ELSE 'PEMILIH' END,
      'is_kandidat', v_is_kandidat,
      'fase', v_fase,
      'is_digunakan', COALESCE(v_penilai.is_digunakan, false),
      'periode', row_to_json(v_periode),
      'profil', jsonb_build_object(
        'id', v_penilai.pegawai_id,
        'nama', v_penilai.nama,
        'nip', v_penilai.nip,
        'nip_baru', v_penilai.nip_baru,
        'jabatan', v_penilai.jabatan,
        'foto_url', v_penilai.foto_url
      )
    );
    RETURN v_res;
  END IF;

  RETURN jsonb_build_object('is_valid', false, 'error', 'Token tidak valid');
END;
$$;

-- RPC: Submit Usulan Pengusul (Fase 1)
CREATE OR REPLACE FUNCTION public.submit_usulan_pionir(
  p_token UUID,
  p_kandidat_id BIGINT,
  p_scores_json JSONB,
  p_kata_kunci TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_pengusul RECORD;
  v_periode RECORD;
  v_item JSONB;
  v_q_id BIGINT;
  v_skor NUMERIC;
BEGIN
  SELECT * INTO v_pengusul 
  FROM public.pengusul_periode 
  WHERE token_akses = p_token;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Token pengusul tidak valid.';
  END IF;

  IF v_pengusul.is_digunakan THEN
    RAISE EXCEPTION 'Anda sudah pernah mengirimkan usulan pada periode ini.';
  END IF;

  SELECT * INTO v_periode 
  FROM public.periode_penilaian 
  WHERE id = v_pengusul.periode_id;

  IF v_periode.status != 'BERJALAN' THEN
    RAISE EXCEPTION 'Periode pemilihan tidak aktif.';
  END IF;

  -- Anti self-nomination
  IF v_pengusul.pegawai_id = p_kandidat_id THEN
    RAISE EXCEPTION 'Pengusul tidak diperbolehkan mencalonkan diri sendiri.';
  END IF;

  -- Pengusul lain tidak boleh dicalonkan
  IF EXISTS (
    SELECT 1 FROM public.pengusul_periode 
    WHERE periode_id = v_pengusul.periode_id AND pegawai_id = p_kandidat_id
  ) THEN
    RAISE EXCEPTION 'Pegawai yang bertindak sebagai Pengusul tidak dapat dicalonkan.';
  END IF;

  -- Pengusul dan kandidat harus berasal dari kantor/wilayah kerja yang sama
  IF (SELECT wilayah_id FROM public.pegawai WHERE id = v_pengusul.pegawai_id) IS NOT NULL AND
     (SELECT wilayah_id FROM public.pegawai WHERE id = p_kandidat_id) IS NOT NULL AND
     (SELECT wilayah_id FROM public.pegawai WHERE id = v_pengusul.pegawai_id) <>
     (SELECT wilayah_id FROM public.pegawai WHERE id = p_kandidat_id) THEN
    RAISE EXCEPTION 'Kandidat harus berasal dari kantor/wilayah yang sama dengan Pengusul.';
  END IF;

  -- 1. Insert ke nominee_periode jika belum ada
  INSERT INTO public.nominee_periode (periode_id, pegawai_id, created_at)
  VALUES (v_pengusul.periode_id, p_kandidat_id, NOW())
  ON CONFLICT DO NOTHING;

  -- 2. Insert skor kuesioner per pertanyaan
  FOR v_item IN SELECT * FROM jsonb_array_elements(p_scores_json)
  LOOP
    v_q_id := (v_item->>'pertanyaan_id')::BIGINT;
    v_skor := (v_item->>'skor')::NUMERIC;

    INSERT INTO public.penilaian_pionir_pengusul (
      periode_id,
      pengusul_id,
      kandidat_id,
      pertanyaan_id,
      skor,
      kata_kunci,
      created_at
    ) VALUES (
      v_pengusul.periode_id,
      v_pengusul.pegawai_id,
      p_kandidat_id,
      v_q_id,
      v_skor,
      TRIM(p_kata_kunci),
      NOW()
    )
    ON CONFLICT (periode_id, pengusul_id, kandidat_id, pertanyaan_id)
    DO UPDATE SET 
      skor = EXCLUDED.skor,
      kata_kunci = EXCLUDED.kata_kunci;
  END LOOP;

  -- 3. Tandai token terpakai
  UPDATE public.pengusul_periode
  SET is_digunakan = TRUE,
      submitted_at = NOW()
  WHERE id = v_pengusul.id;

  RETURN jsonb_build_object('success', true, 'message', 'Usulan dan penilaian berhasil dikirim.');
END;
$$;

-- RPC: Submit Vote Pemilih Biasa (Fase 2 - Mode Rahasia LUBER)
CREATE OR REPLACE FUNCTION public.submit_vote_pionir(
  p_token UUID,
  p_kandidat_id BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_penilai RECORD;
  v_periode RECORD;
  v_hash TEXT;
BEGIN
  SELECT * INTO v_penilai 
  FROM public.akses_penilai 
  WHERE token_akses = p_token;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Token pemilih tidak valid.';
  END IF;

  IF v_penilai.is_digunakan THEN
    RAISE EXCEPTION 'Anda sudah menggunakan hak suara Anda.';
  END IF;

  -- Kandidat dilarang vote
  IF EXISTS (
    SELECT 1 FROM public.nominee_periode 
    WHERE periode_id = v_penilai.periode_id AND pegawai_id = v_penilai.pegawai_id
  ) THEN
    RAISE EXCEPTION 'Kandidat tidak memiliki hak suara dalam pemilihan.';
  END IF;

  SELECT * INTO v_periode 
  FROM public.periode_penilaian 
  WHERE id = v_penilai.periode_id;

  IF v_periode.status != 'BERJALAN' THEN
    RAISE EXCEPTION 'Periode pemilihan tidak aktif.';
  END IF;

  IF v_periode.tgl_selesai_fase1 IS NOT NULL AND NOW() <= v_periode.tgl_selesai_fase1 THEN
    RAISE EXCEPTION 'Tahap voting umum belum dibuka. Mohon tunggu hingga fase pengusulan selesai.';
  END IF;

  v_hash := md5(p_token::text || NOW()::text);

  INSERT INTO public.suara_pionir (
    periode_id,
    kandidat_id,
    voter_hash,
    created_at
  ) VALUES (
    v_penilai.periode_id,
    p_kandidat_id,
    v_hash,
    NOW()
  );

  UPDATE public.akses_penilai
  SET is_digunakan = TRUE,
      submitted_at = NOW()
  WHERE id = v_penilai.id;

  RETURN jsonb_build_object('success', true, 'message', 'Suara Anda berhasil tercatat secara rahasia.');
END;
$$;

-- RPC: Ambil Daftar Kandidat Resmi Mode PIONIR beserta Testimoni Pengusul
CREATE OR REPLACE FUNCTION public.get_kandidat_pionir_periode(p_periode_id BIGINT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_res JSONB;
BEGIN
  SELECT jsonb_agg(
    jsonb_build_object(
      'id', p.id,
      'nama', p.nama,
      'nip', p.nip,
      'nip_baru', p.nip_baru,
      'jabatan', p.jabatan,
      'foto_url', p.foto_url,
      'unit_kerja', w.nama_wilayah,
      'jumlah_pengusul', COALESCE(sub.jml_pengusul, 0),
      'kata_pengusul', COALESCE(sub.kumpulan_kata, '')
    )
  ) INTO v_res
  FROM public.nominee_periode np
  JOIN public.pegawai p ON p.id = np.pegawai_id
  LEFT JOIN public.wilayah w ON w.id = p.wilayah_id
  LEFT JOIN (
    SELECT 
      kandidat_id,
      COUNT(DISTINCT pengusul_id) AS jml_pengusul,
      STRING_AGG(DISTINCT TRIM(kata_kunci), ', ') FILTER (WHERE kata_kunci IS NOT NULL AND TRIM(kata_kunci) != '') AS kumpulan_kata
    FROM public.penilaian_pionir_pengusul
    WHERE periode_id = p_periode_id
    GROUP BY kandidat_id
  ) sub ON sub.kandidat_id = p.id
  WHERE np.periode_id = p_periode_id;

  RETURN COALESCE(v_res, '[]'::jsonb);
END;
$$;

-- RPC: Update Nilai CKP Kandidat oleh Admin
CREATE OR REPLACE FUNCTION public.update_ckp_kandidat_pionir(
  p_periode_id BIGINT,
  p_nominee_id BIGINT,
  p_nilai_ckp NUMERIC
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.nominee_periode
  SET nilai_ckp = p_nilai_ckp
  WHERE periode_id = p_periode_id AND pegawai_id = p_nominee_id;
END;
$$;

-- RPC: Simpan Tim Pengusul oleh Admin (Security Definer)
CREATE OR REPLACE FUNCTION public.simpan_pengusul_pionir(
  p_periode_id BIGINT,
  p_pegawai_ids BIGINT[]
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.pengusul_periode (periode_id, pegawai_id)
  SELECT p_periode_id, unnest(p_pegawai_ids)
  ON CONFLICT (periode_id, pegawai_id) DO NOTHING;
